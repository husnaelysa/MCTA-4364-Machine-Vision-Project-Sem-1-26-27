"""## 4. Inference — Anomaly Map Computation

At test time we compute:

$$\mathcal{A}(x)_{h,w} = \frac{1}{C}\sum_c \left( \hat{T}(x)_{c,h,w} - S(x)_{c,h,w} \right)^2$$

where $\hat{T}$ denotes the channel-normalised teacher features.

**Post-processing:**
1. **Upsample** the anomaly map from $(H', W')$ to the original $(H, W)$ using bilinear interpolation.
2. **Gaussian smoothing** ($\sigma = 4$) to suppress noise and produce cleaner boundaries.
3. **Image-level score** = $\max_{h,w} \mathcal{A}(x)_{h,w}$ (maximum anomaly value).

We also compute the **AUROC** at both image level and pixel level to evaluate detection quality.
"""

from sklearn.metrics import roc_auc_score

# ── Inference ─────────────────────────────────────────────────
@torch.no_grad()
def predict(teacher, student, loader, t_mean, t_std, device, img_size=IMAGE_SIZE, sigma=4):
    """Run inference — return anomaly maps, labels, masks, image paths."""
    teacher.eval()
    student.eval()

    all_maps = []
    all_labels = []
    all_masks = []
    all_paths = []

    for imgs, masks, labels, defect_types in loader:
        imgs = imgs.to(device)
        t_feats = teacher(imgs)
        t_feats = normalise_teacher_features(t_feats, t_mean, t_std)
        s_feats = student(imgs)

        diff = (t_feats - s_feats) ** 2       # (B, C, H', W')
        amap = diff.mean(dim=1, keepdim=True)  # (B, 1, H', W')
        # Upsample to input resolution
        amap = F.interpolate(amap, size=(img_size, img_size), mode="bilinear", align_corners=False)
        amap = amap.squeeze(1).cpu().numpy()   # (B, H, W)

        for i in range(amap.shape[0]):
            smoothed = gaussian_filter(amap[i], sigma=sigma)
            all_maps.append(smoothed)
            all_labels.append(labels[i].item())
            all_masks.append(masks[i].squeeze(0).numpy())
            all_paths.append(defect_types[i])

    return all_maps, all_labels, all_masks, all_paths


anomaly_maps, labels, gt_masks, img_paths = predict(
    teacher, student, test_loader, t_mean, t_std, DEVICE
)

# ── Image-level AUROC ────────────────────────────────────────
image_scores = [m.max() for m in anomaly_maps]
