    # Anneal hard-mining percentile from 0.999 → 0.99
    p_hard = 1.0 - (1.0 - 0.999) * (1.0 - (epoch - 1) / NUM_EPOCHS)  # starts ~0.999, ends ~0.99

    for imgs, *_ in train_loader:
        imgs = imgs.to(DEVICE)

        with torch.no_grad():
            t_feats = teacher(imgs)
            t_feats = normalise_teacher_features(t_feats, t_mean, t_std)

        s_feats = student(imgs)
        loss = kd_loss_with_hard_mining(t_feats, s_feats, p_hard)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        epoch_loss += loss.item() * imgs.size(0)

    scheduler.step()
    avg_loss = epoch_loss / len(train_ds)
    loss_history.append(avg_loss)

