"""## 3. Training — Knowledge Distillation

### Loss function

For each training image $x$ (normal only):

$$\mathcal{L}_{\text{KD}}(x) = \frac{1}{C \cdot H' \cdot W'} \sum_{c,h,w} \left( T(x)_{c,h,w} - S(x)_{c,h,w} \right)^2$$

### Hard example mining

Following EfficientAD, we keep only the **hardest $p$\%** of spatial positions per image to prevent the student from becoming too good too quickly:

$$\mathcal{L}_{\text{hard}}(x) = \text{mean}\!\Big(\text{top-}p\%\big(\| T(x) - S(x) \|^2\big)\Big)$$

The percentile $p$ is annealed: $p_{\text{hard}} = 1 - (1 - p_{\min}) \cdot \frac{\text{epoch}}{\text{total epochs}}$ where $p_{\min} = 0.999$ initially → $0.99$ at the end.

### Normalisation of teacher outputs

Before computing the loss, we **channel-wise normalise** teacher outputs using running mean/std computed over the training set. This stabilises training and makes anomaly scores comparable across channels.
"""

# ── Compute channel-wise mean / std of teacher outputs ───────
@torch.no_grad()
def compute_teacher_stats(teacher, loader, device):
    """Compute channel-wise mean and std of teacher feature maps over a dataset."""
    channels_sum = None
    channels_sq_sum = None
    num_pixels = 0

    for imgs, *_ in loader:
        imgs = imgs.to(device)
        feats = teacher(imgs)  # (B, C, H', W')
        B, C, H, W = feats.shape
        feats_flat = feats.permute(1, 0, 2, 3).reshape(C, -1)  # (C, B*H*W)
        if channels_sum is None:
            channels_sum = feats_flat.sum(dim=1)
            channels_sq_sum = (feats_flat ** 2).sum(dim=1)
        else:
            channels_sum += feats_flat.sum(dim=1)
            channels_sq_sum += (feats_flat ** 2).sum(dim=1)
        num_pixels += B * H * W

    mean = channels_sum / num_pixels           # (C,)
    std = torch.sqrt(channels_sq_sum / num_pixels - mean ** 2)  # (C,)
    return mean, std

teacher_mean, teacher_std = compute_teacher_stats(teacher, train_loader, DEVICE)
print(f"Teacher feature stats — mean range: [{teacher_mean.min():.3f}, {teacher_mean.max():.3f}], "
      f"std range: [{teacher_std.min():.3f}, {teacher_std.max():.3f}]")

# ── Training loop ─────────────────────────────────────────────

def normalise_teacher_features(feats, mean, std):
    """Channel-wise normalise teacher features."""
    return (feats - mean[None, :, None, None]) / (std[None, :, None, None] + 1e-6)


def kd_loss_with_hard_mining(t_feats, s_feats, p_hard):
    """MSE loss with hard-example mining: keep top p_hard fraction of pixels."""
    diff = (t_feats - s_feats) ** 2          # (B, C, H, W)
    pixel_loss = diff.mean(dim=1)            # (B, H, W) — average over channels
    B, H, W = pixel_loss.shape
    flat = pixel_loss.view(B, -1)            # (B, H*W)
    k = max(1, int(flat.shape[1] * p_hard))
    topk_vals, _ = flat.topk(k, dim=1)
    return topk_vals.mean()


