# ── Teacher: frozen ResNet-18 feature extractor ─────────────
class TeacherEncoder(nn.Module):
    """Extract multi-scale features from a pretrained ResNet-18 and
    project them to `out_channels` dimensions."""

    def __init__(self, out_channels: int = OUT_CHANNELS):
        super().__init__()
        resnet = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
        # Use layers up to layer2 — gives stride-4 and stride-8 feature maps
        self.layer1 = nn.Sequential(resnet.conv1, resnet.bn1, resnet.relu, resnet.maxpool, resnet.layer1)
        self.layer2 = resnet.layer2   # 128-ch, stride 8 (H/8, W/8)

        # 1×1 conv to project concatenated features → out_channels
        self.proj = nn.Conv2d(64 + 128, out_channels, kernel_size=1, bias=False)

        # Freeze everything
        for p in self.parameters():
            p.requires_grad = False

    @torch.no_grad()
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        f1 = self.layer1(x)            # (B,  64, H/4, W/4)
        f2 = self.layer2(f1)           # (B, 128, H/8, W/8)
        # Upsample f2 to match f1 spatial size
        f2_up = F.interpolate(f2, size=f1.shape[2:], mode="bilinear", align_corners=False)
        cat = torch.cat([f1, f2_up], dim=1)  # (B, 192, H/4, W/4)
        return self.proj(cat)                 # (B, out_channels, H/4, W/4)


# ── Student: Patch Description Network (PDN-Small) ──────────
class PDNSmall(nn.Module):
    """Lightweight student network from EfficientAD."""

    def __init__(self, out_channels: int = OUT_CHANNELS):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(3, 128, kernel_size=4, stride=1, padding=3),
            nn.ReLU(inplace=True),
            nn.AvgPool2d(2, stride=2, padding=1),
            nn.Conv2d(128, 256, kernel_size=4, stride=1, padding=3),
            nn.ReLU(inplace=True),
            nn.AvgPool2d(2, stride=2, padding=1),
            nn.Conv2d(256, 256, kernel_size=3, stride=1, padding=1),
            nn.ReLU(inplace=True),
            nn.Conv2d(256, out_channels, kernel_size=4, stride=1, padding=0),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)


