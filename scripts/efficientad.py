"""## 1. Model Definitions

### Teacher Network

We use a **pretrained ResNet-18** as the teacher. We extract features from `layer1` (64-ch, stride 4) and `layer2` (128-ch, stride 8), upsample `layer2` to match `layer1`'s spatial size, then project the concatenated 192-ch map to `OUT_CHANNELS = 384` via a 1×1 convolution. The teacher is **frozen** — no gradients flow through it.

The output resolution is **H/4 × W/4** = **64 × 64** for a 256 × 256 input.

### Student Network — Patch Description Network (PDN)

The PDN follows the EfficientAD "small" variant:

| Layer | Type | Kernel | Stride | Padding | Out Channels |
|-------|------|--------|--------|---------|-------------|
| 1 | Conv2d + ReLU | 4×4 | 1 | 3 | 128 |
| 2 | AvgPool2d | 2×2 | 2 | 1 | — |
| 3 | Conv2d + ReLU | 4×4 | 1 | 3 | 256 |
| 4 | AvgPool2d | 2×2 | 2 | 1 | — |
| 5 | Conv2d + ReLU | 3×3 | 1 | 1 | 256 |
| 6 | Conv2d | 4×4 | 1 | 0 | 384 |

The student also produces **64 × 64** feature maps from a 256 × 256 input, matching the teacher exactly.

"""

